import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
UNITY=ROOT/'clients/unity/Assets/VrCommand/Resources/VrCommand'
WEB=ROOT/'src/VrCommand.Api/wwwroot/console'
PIN='b8fe83d66781c2f65816d6873cc08ba01314418d42777a55e9eea2d1ee34a9bb'
spec=importlib.util.spec_from_file_location('fixed_armed',ROOT/'scripts/generate-armed-combatants.py')
armed=importlib.util.module_from_spec(spec);spec.loader.exec_module(armed)

def outputs():
    armed.outputs() # Verify the retained armed geometry and its source pins.
    mesh=armed.old.Mesh();loop=[]
    for i in range(16):
        a=i*math.pi/8;r=.065 if i%2==0 else .026;loop.append([r*math.cos(a),r*math.sin(a),.055])
    for i in range(16):
        j=(i+1)%16;color=[1,.9,.45,1] if i%2==0 else [1,.5,.04,1]
        mesh.face([loop[i],loop[j],[0,0,.24]],color);mesh.face([loop[j],loop[i],[0,0,0]],color)
    data={'assetSet':'combat-effects-v1','units':'metres','origin':'accepted-enemy-shot','forward':'+Z','enemyFireVersion':1,
          'mesh':armed.old.mesh_data('EnemyMuzzleFlash',mesh)}
    encoded=json.dumps(data,separators=(',',':'))+'\n';digest=hashlib.sha256(encoded.encode()).hexdigest()
    if digest!=PIN:raise SystemExit('combat-effects-v1 is frozen; use a new profile. SHA256: '+digest)
    provenance={'assetSet':data['assetSet'],'source':'Original fictional opaque game muzzle pulse; no external assets',
        'generator':'scripts/generate-combat-effects.py','armedSourceSha256':armed.PIN,'dataSha256':digest,'triangles':len(mesh.triangles)//3,
        'scope':'Enemy shot flash at its saved ray, cosmetic sidearm recoil; no gameplay, tracking, light, audio or ballistic changes'}
    return {UNITY/'combat-effects-v1.json':encoded,UNITY/'combat-effects-provenance.json':json.dumps(provenance,indent=2)+'\n',
            WEB/'combat-effects-data.js':'// Generated by scripts/generate-combat-effects.py; do not edit.\nexport const COMBAT_EFFECTS = '+encoded.rstrip()+';\n'}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,value in outputs().items():
        if a.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=value:raise SystemExit('Combat effects mismatch: '+str(path))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value,encoding='utf-8',newline='\n')
    print('Verified combat-effects-v1 geometry and provenance' if a.check else 'Generated combat-effects-v1 geometry and provenance')

if __name__=='__main__':main()
