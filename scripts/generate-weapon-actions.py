"""Split the frozen fictional rifle for cosmetic reloads; add original gloves."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
UNITY=ROOT/'clients/unity/Assets/VrCommand/Resources/VrCommand'
WEB=ROOT/'src/VrCommand.Api/wwwroot/console'
PIN='517c3616ec12dad34f25cc50f5309eae1033b62bcbbb636b4a3f378a5c12cab3'
spec=importlib.util.spec_from_file_location('original_rifle',ROOT/'scripts/generate-service-rifle.py')
rifle=importlib.util.module_from_spec(spec);spec.loader.exec_module(rifle)

def subset(source,indices,kind,pivot):
    result={'kind':kind,'positions':[],'normals':[],'colors':[],'triangles':[]};mapping={}
    for index in indices:
        if index not in mapping:
            mapping[index]=len(mapping)
            result['positions'].extend(round(source['positions'][index*3+k]-pivot[k],7) for k in range(3))
            result['normals'].extend(source['normals'][index*3:index*3+3]);result['colors'].extend(source['colors'][index*4:index*4+4])
        result['triangles'].append(mapping[index])
    return result

def glove(left):
    mesh=rifle.Mesh();colour=[.16,.19,.13,1];pads=[.25,.28,.19,1]
    mesh.box(.055,.09,-.04,.045,-.055,.055,colour)
    for z in [-.05,-.025,0,.025]:
        mesh.box(-.055,.06,-.06,-.035,z,z+.02,pads)
        mesh.box(-.075,-.05,-.035,.03,z,z+.02,colour)
    mesh.box(.035,.075,.025,.065,.02,.065,pads)
    if left:
        mesh.positions=[-v if i%3==0 else v for i,v in enumerate(mesh.positions)]
        mesh.normals=[-v if i%3==0 else v for i,v in enumerate(mesh.normals)]
        for i in range(0,len(mesh.triangles),3):mesh.triangles[i+1],mesh.triangles[i+2]=mesh.triangles[i+2],mesh.triangles[i+1]
    return {'kind':'LeftGlove' if left else 'RightGlove','positions':mesh.positions,'normals':mesh.normals,'colors':mesh.colors,'triangles':mesh.triangles}

def outputs():
    # The old generator checks its original SHA before any split. No old asset is changed.
    source=json.loads(rifle.outputs()[UNITY/'service-rifle-v1.json'])['mesh'];body=[];mag=[]
    for i in range(0,len(source['triangles']),3):
        tri=source['triangles'][i:i+3];points=[source['positions'][n*3:n*3+3] for n in tri]
        is_mag=all(abs(x)<=.038001 and -.270001<=y<=-.074999 and -.460001<=z<=-.344999 for x,y,z in points)
        (mag if is_mag else body).extend(tri)
    assert len(mag)//3==24 and len(body)//3==240
    pivot=[0,-.075,-.4025]
    data={'assetSet':'weapon-actions-v1','units':'metres','origin':'muzzle','forward':'+Z','weaponPresentationVersion':1,
          'magazinePivot':pivot,'parts':[subset(source,body,'Body',[0,0,0]),subset(source,mag,'Magazine',pivot),glove(False),glove(True)]}
    encoded=json.dumps(data,separators=(',',':'))+'\n';digest=hashlib.sha256(encoded.encode()).hexdigest()
    if digest!=PIN:raise SystemExit('weapon-actions-v1 is frozen; use a new profile. SHA256: '+digest)
    provenance={'assetSet':data['assetSet'],'source':'Original fictional decorative rifle split and gloves; no external models or textures',
        'generator':'scripts/generate-weapon-actions.py','rifleSourceSha256':rifle.FROZEN_V1_SHA256,'dataSha256':digest,
        'triangles':{p['kind']:len(p['triangles'])//3 for p in data['parts']},'scope':'Cosmetic magazine / simulated gloves only; no collider, tracking or weapon-rule changes'}
    return {UNITY/'weapon-actions-v1.json':encoded,UNITY/'weapon-actions-provenance.json':json.dumps(provenance,indent=2)+'\n',
        WEB/'weapon-actions-data.js':'// Generated by scripts/generate-weapon-actions.py; do not edit.\nexport const WEAPON_ACTIONS = '+encoded.rstrip()+';\n'}

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for p,value in outputs().items():
        if args.check:
            if not p.is_file() or p.read_text(encoding='utf-8')!=value:raise SystemExit('Weapon actions mismatch: '+str(p))
        else:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(value,encoding='utf-8',newline='\n')
    print('Verified weapon-actions-v1 geometry and provenance' if args.check else 'Generated weapon-actions-v1 geometry and provenance')

if __name__=='__main__':main()
