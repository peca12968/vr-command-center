"""Original compact sidearm and cosmetic two-arm opponent. Retains all published profiles."""
import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
UNITY=ROOT/'clients/unity/Assets/VrCommand/Resources/VrCommand'
WEB=ROOT/'src/VrCommand.Api/wwwroot/console'
PIN='cc011e951163d4b846c4e2c217592251906844c0dfcee2f795618c8c1c388102'

def load(name,file):
    spec=importlib.util.spec_from_file_location(name,ROOT/'scripts'/file)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);return module

old=load('frozen_combatants','generate-combatants.py')
actions=load('frozen_actions','generate-weapon-actions.py')

def build():
    original=json.loads(old.outputs()[UNITY/'combatants-v1.json'])
    gloves=json.loads(actions.outputs()[UNITY/'weapon-actions-v1.json'])
    torso=old.Mesh()
    torso.box(-.205,.205,.82,1.43,-.38,-.14,old.UNIFORM)
    torso.box(-.08,.08,1.40,1.53,-.325,-.195,old.UNIFORM)
    torso.box(-.19,.19,.96,1.38,-.405,-.115,old.VEST)
    torso.box(-.21,.21,.82,.90,-.29,-.03,old.DARK)
    for x in [-.115,0,.115]:torso.box(x-.045,x+.045,1.03,1.20,-.115,-.07,old.VEST)
    upper=old.Mesh();upper.box(-.045,.045,0,1,-.045,.045,old.UNIFORM)
    upper.box(-.047,.047,.15,.35,-.047,.047,old.BAND)
    lower=old.Mesh();lower.box(-.038,.038,0,1,-.038,.038,old.UNIFORM)
    lower.box(-.04,.04,.03,.18,-.04,.04,old.VEST)
    pistol=old.Mesh()
    pistol.box(-.026,.026,-.02,.04,-.175,-.006,old.DARK)
    pistol.box(-.023,.023,-.055,-.02,-.14,-.015,old.MASK)
    pistol.box(-.025,.025,-.18,-.05,-.10,-.04,old.DARK)
    pistol.box(-.026,.026,-.13,-.06,-.045,-.035,old.MASK)
    pistol.box(-.008,.008,.04,.05,-.025,-.015,old.VEST)
    pistol.box(-.018,.018,.04,.05,-.165,-.155,old.VEST)
    pistol.box(-.012,.012,-.006,.018,-.006,0,old.MASK)
    parts=[old.mesh_data('Torso',torso),copy.deepcopy(original['parts'][1]),copy.deepcopy(original['parts'][2]),
           old.mesh_data('UpperArm',upper),old.mesh_data('LowerArm',lower),old.mesh_data('Sidearm',pistol)]
    for part in gloves['parts'][2:]:
        part=copy.deepcopy(part);part['positions']=[round(v*.65,7) for v in part['positions']];parts.append(part)
    return {'assetSet':'armed-combatants-v1','units':'metres','origin':'feet','forward':'+Z','enemyPresentationVersion':1,
            'headPivot':[0,1.51,-.26],'leftHip':[-.11,.82,-.08],'rightHip':[.11,.82,-.08],
            'muzzle':[0,1.4,0],'leftGrip':[0,-.085,-.035],'rightGrip':[0,-.11,-.075],'parts':parts}

def outputs():
    data=build();encoded=json.dumps(data,separators=(',',':'))+'\n';digest=hashlib.sha256(encoded.encode()).hexdigest()
    if digest!=PIN:raise SystemExit('armed-combatants-v1 is frozen; use a new profile. SHA256: '+digest)
    counts={p['kind']:len(p['triangles'])//3 for p in data['parts']}
    total=sum(n*(2 if k in ['Leg','UpperArm','LowerArm'] else 1) for k,n in counts.items())
    provenance={'assetSet':data['assetSet'],'source':'Original fictional compact sidearm and two-arm opponent; no external art',
        'generator':'scripts/generate-armed-combatants.py','combatantsSha256':old.FROZEN_V1_SHA256,'weaponActionsSha256':actions.PIN,
        'dataSha256':digest,'triangles':counts,'totalPerEnemy':total,
        'scope':'Cosmetic compressed two-hand stance and two-bone solve; original authority muzzle/box/rules unchanged. No tracked hands, recoil, flash or foot IK.'}
    return {UNITY/'armed-combatants-v1.json':encoded,UNITY/'armed-combatants-provenance.json':json.dumps(provenance,indent=2)+'\n',
            WEB/'armed-combatants-data.js':'// Generated by scripts/generate-armed-combatants.py; do not edit.\nexport const ARMED_COMBATANTS = '+encoded.rstrip()+';\n'}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,value in outputs().items():
        if a.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=value:raise SystemExit('Armed geometry mismatch: '+str(path))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value,encoding='utf-8',newline='\n')
    print('Verified armed-combatants-v1 geometry and provenance' if a.check else 'Generated armed-combatants-v1 geometry and provenance')

if __name__=='__main__':main()

