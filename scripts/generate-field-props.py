"""Generate original low-poly field props for Unity and the local replay viewer.

Metres, Y up, feet origin; shared positions / winding / normals / vertex colours.
No external models, textures, fonts, downloads or random inputs.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNITY = ROOT / 'clients/unity/Assets/VrCommand/Resources/VrCommand'
WEB = ROOT / 'src/VrCommand.Api/wwwroot/console'
TAN = [.49, .40, .25, 1]
DARK = [.17, .19, .14, 1]
OLIVE = [.23, .29, .20, 1]
AMBER = [.76, .59, .22, 1]
# Published profiles are immutable. New geometry / colours require a new ID and
# retained old data, not an update to this pin under the existing v1 identity.
FROZEN_V1_SHA256 = '7911140960f5e947f4cb7c474913608d7db5c1bec7c3558ffd9aac81eb6e3dc2'


class Mesh:
    def __init__(self):
        self.positions = []; self.normals = []; self.colors = []; self.triangles = []

    def face(self, points, color):
        a, b, c = points[:3]; u = [b[i] - a[i] for i in range(3)]; v = [c[i] - a[i] for i in range(3)]
        n = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
        length = math.sqrt(sum(x*x for x in n)); assert length > 1e-9
        start = len(self.positions)//3
        for p in points:
            self.positions.extend(round(x, 7) for x in p); self.normals.extend(round(x/length, 7) for x in n); self.colors.extend(color)
        for i in range(1, len(points)-1): self.triangles.extend([start, start+i, start+i+1])

    def sack(self, x, y, width, shade):
        # Octagonal XY silhouette extruded in Z: chamfered corners, no high-poly subdivision.
        w = width/2; h = .15; bevel = .045
        loop = [(-w+bevel,-h),(w-bevel,-h),(w,-h+bevel),(w,h-bevel),(w-bevel,h),(-w+bevel,h),(-w,h-bevel),(-w,-h+bevel)]
        front = [(x+a, y+b, .35) for a,b in loop]; back = [(x+a, y+b, -.35) for a,b in loop]
        color = [round(c*shade, 4) for c in TAN[:3]]+[1]
        self.face(front, color); self.face(list(reversed(back)), color)
        for i in range(8):
            j=(i+1)%8; self.face([back[i],back[j],front[j],front[i]], color)
        # Narrow sewn line across each visible face; lies inside the cover envelope.
        for z, reverse in [(.35001, False),(-.35001, True)]:
            line=[(x-w+.07,y-.006,z),(x+w-.07,y-.006,z),(x+w-.07,y+.006,z),(x-w+.07,y+.006,z)]
            self.face(list(reversed(line)) if reverse else line, DARK)

    def drum(self):
        # Twelve sides with rolled rims and two strengthening hoops.
        rings=[(0,.32),(.025,.35),(.065,.35),(.085,.325),(.29,.325),(.30,.35),(.34,.35),(.35,.325),
               (.85,.325),(.86,.35),(.90,.35),(.91,.325),(1.115,.325),(1.135,.35),(1.175,.35),(1.2,.32)]
        n=12
        loop=lambda y,r:[(r*math.cos(i*2*math.pi/n),y,r*math.sin(i*2*math.pi/n)) for i in range(n)]
        for index, ((y0,r0),(y1,r1)) in enumerate(zip(rings,rings[1:])):
            a,b=loop(y0,r0),loop(y1,r1)
            color = AMBER if index in [5,9] else DARK if index in [1,13] else OLIVE
            for i in range(n):
                j=(i+1)%n; self.face([a[j],a[i],b[i],b[j]],color)
        self.face(loop(0,.32),DARK); self.face(list(reversed(loop(1.2,.32))),OLIVE)
        # Inset fill cap on the lid; top remains at 1.2m.
        cap=[(.12+.055*math.cos(i*math.pi/4),1.20001,.08+.055*math.sin(i*math.pi/4)) for i in range(8)]
        self.face(list(reversed(cap)),DARK)

    def data(self, kind): return {'kind':kind, 'positions':self.positions,'normals':self.normals,'colors':self.colors,'triangles':self.triangles}


def outputs():
    bags = Mesh()
    for row,count in enumerate([3,2,3]):
        width=2/count
        for col in range(count): bags.sack(-1+width*(col+.5),.15+row*.3,width,1+(.04 if (row+col)%2 else -.03))
    drum=Mesh();drum.drum()
    data={'assetSet':'field-props-v1','units':'metres','origin':'feet','props':[bags.data('Sandbag'),drum.data('Barrel')]}
    encoded=json.dumps(data,separators=(',',':'))+'\n'
    if hashlib.sha256(encoded.encode()).hexdigest() != FROZEN_V1_SHA256:
        raise SystemExit('field-props-v1 is frozen; introduce a new assetSet and preserve v1 data / readers')
    provenance={'assetSet':data['assetSet'],'source':'Original procedural geometry; no external meshes, textures or fonts',
        'generator':'scripts/generate-field-props.py','dataSha256':hashlib.sha256(encoded.encode()).hexdigest(),
        'triangles':{p['kind']:len(p['triangles'])//3 for p in data['props']}}
    return {UNITY/'field-props-v1.json':encoded, WEB/'field-props-data.js':'// Generated by scripts/generate-field-props.py; do not edit.\nexport const FIELD_PROPS = '+encoded.rstrip()+';\n',
        UNITY/'field-props-provenance.json':json.dumps(provenance,indent=2)+'\n'}


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content: raise SystemExit('Generated field prop mismatch: '+str(path))
        else: path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content,encoding='utf-8',newline='\n')
    print('Verified original field-props-v1 geometry / browser copy / provenance' if args.check else 'Generated field-props-v1 geometry / browser copy / provenance')


if __name__=='__main__':main()
