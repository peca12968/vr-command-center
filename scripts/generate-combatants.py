"""Original fictional low-poly opponent; shared Unity/replay geometry, no external art."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('original_mesh_builder', ROOT / 'scripts/generate-service-rifle.py')
builder = importlib.util.module_from_spec(spec); spec.loader.exec_module(builder)
Mesh = builder.Mesh
UNITY = ROOT / 'clients/unity/Assets/VrCommand/Resources/VrCommand'
WEB = ROOT / 'src/VrCommand.Api/wwwroot/console'
FROZEN_V1_SHA256 = '39fa5e9baceec0eb71ce6a4664fc4460e7b0f212f2c58b75c7b4d75b3565fdf2'
UNIFORM = [.40,.29,.22,1]
VEST = [.20,.25,.18,1]
DARK = [.085,.10,.085,1]
HELMET = [.32,.36,.23,1]
MASK = [.27,.29,.25,1]
BAND = [.68,.22,.16,1]


def mesh_data(kind, mesh):
    return {'kind':kind,'positions':mesh.positions,'normals':mesh.normals,'colors':mesh.colors,'triangles':mesh.triangles}


def outputs():
    torso=Mesh()
    torso.box(-.205,.205,.82,1.43,-.12,.12,UNIFORM)
    torso.box(-.08,.08,1.40,1.53,-.065,.065,UNIFORM)
    torso.box(-.19,.19,.96,1.38,-.145,.145,VEST)
    torso.box(-.21,.21,.82,.90,-.13,.13,DARK)
    for x in [-.115,0,.115]: torso.box(x-.045,x+.045,1.03,1.20,.145,.19,VEST)
    # Bent arms remain decorative. No unrecorded NPC weapon or grip pose.
    for side in [-1,1]:
        x0,x1=sorted([side*.20,side*.28])
        torso.box(x0,x1,1.18,1.41,-.08,.065,UNIFORM)
        torso.box(x0-.002,x1+.002,1.28,1.33,-.083,.068,BAND)
        x0,x1=sorted([side*.14,side*.24])
        torso.box(x0,x1,1.12,1.20,.02,.18,UNIFORM)
        torso.box(x0,x1,1.10,1.20,.16,.22,DARK)
    head=Mesh()
    head.box(-.065,.065,0,.08,-.065,.065,MASK)
    head.prism([(-.09,.06),(.09,.06),(.12,.10),(.12,.21),(.08,.25),(-.08,.25),(-.12,.21),(-.12,.10)],-.105,.105,MASK)
    head.box(-.125,.125,.145,.195,.105,.118,DARK)
    head.box(-.07,.07,.07,.145,.105,.128,MASK)
    head.prism([(-.12,.19),(.12,.19),(.14,.22),(.14,.27),(.10,.29),(-.10,.29),(-.14,.27),(-.14,.22)],-.13,.13,HELMET)
    head.box(-.14,.14,.19,.21,-.14,.145,DARK)
    leg=Mesh()
    # Local hip origin, reused at x=+/-0.11,y=.82. Boots keep floor clearance.
    leg.box(-.075,.075,-.37,0,-.085,.085,UNIFORM)
    leg.box(-.070,.070,-.63,-.37,-.075,.075,UNIFORM)
    leg.box(-.08,.08,-.43,-.30,.075,.105,VEST)
    leg.box(-.08,.08,-.80,-.63,-.10,.14,DARK)
    leg.box(-.082,.082,-.80,-.765,-.103,.143,MASK)
    data={'assetSet':'combatants-v1','units':'metres','origin':'feet','forward':'+Z','enemyPresentationVersion':1,
          'parts':[mesh_data('Torso',torso),mesh_data('Head',head),mesh_data('Leg',leg)],
          'headPivot':[0,1.51,0],'leftHip':[-.11,.82,0],'rightHip':[.11,.82,0]}
    encoded=json.dumps(data,separators=(',',':'))+'\n'; digest=hashlib.sha256(encoded.encode()).hexdigest()
    if digest != FROZEN_V1_SHA256: raise SystemExit('combatants-v1 is frozen; retain it and use a new profile. Actual SHA256: '+digest)
    triangles={part['kind']:len(part['triangles'])//3 for part in data['parts']}
    provenance={'assetSet':data['assetSet'],'source':'Original fictional opponent geometry; no external models, textures or fonts',
                'generator':'scripts/generate-combatants.py','meshBuilder':'scripts/generate-service-rifle.py','dataSha256':digest,
                'triangles':triangles,'totalPerEnemy':triangles['Torso']+triangles['Head']+triangles['Leg']*2,
                'scope':'Decorative head/torso/legs, no collider, weapon, IK or tracking claims'}
    return {UNITY/'combatants-v1.json':encoded,UNITY/'combatants-provenance.json':json.dumps(provenance,indent=2)+'\n',
            WEB/'combatants-data.js':'// Generated by scripts/generate-combatants.py; do not edit.\nexport const COMBATANTS = '+encoded.rstrip()+';\n'}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,content in outputs().items():
        if a.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=content: raise SystemExit('Combatant geometry mismatch: '+str(path))
        else: path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content,encoding='utf-8',newline='\n')
    print('Verified original combatants-v1 geometry and provenance' if a.check else 'Generated original combatants-v1 geometry and provenance')


if __name__=='__main__':main()
