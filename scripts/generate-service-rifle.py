"""Generate an original fictional game rifle, shared by Unity and replay.

Metres, Y up; local origin is the accepted shot muzzle and forward is +Z.
This is a decorative game mesh, not a real weapon design or ballistic model.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNITY = ROOT / 'clients/unity/Assets/VrCommand/Resources/VrCommand'
WEB = ROOT / 'src/VrCommand.Api/wwwroot/console'
FROZEN_V1_SHA256 = 'b054b9780b19104c6ff33a2384df15e9e4f6e2c73293297c4f70e2dd0d8eda25'
STEEL = [.18, .21, .23, 1]
EDGE = [.30, .34, .35, 1]
POLYMER = [.28, .33, .22, 1]
DARK = [.065, .075, .08, 1]
MARK = [.75, .62, .25, 1]


class Mesh:
    def __init__(self):
        self.positions = []; self.normals = []; self.colors = []; self.triangles = []

    def face(self, points, color):
        a,b,c=points[:3]; u=[b[i]-a[i] for i in range(3)]; v=[c[i]-a[i] for i in range(3)]
        n=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]]
        length=math.sqrt(sum(x*x for x in n)); assert length>1e-9
        start=len(self.positions)//3
        for p in points:
            self.positions.extend(round(x,7) for x in p); self.normals.extend(round(x/length,7) for x in n); self.colors.extend(color)
        for i in range(1,len(points)-1): self.triangles.extend([start,start+i,start+i+1])

    def prism(self, loop, back, front, color):
        a=[(x,y,back) for x,y in loop]; b=[(x,y,front) for x,y in loop]
        self.face(list(reversed(a)),color); self.face(b,color)
        for i in range(len(loop)):
            j=(i+1)%len(loop); self.face([a[i],a[j],b[j],b[i]],color)

    def box(self, x0,x1,y0,y1,z0,z1,color):
        self.prism([(x0,y0),(x1,y0),(x1,y1),(x0,y1)],z0,z1,color)

    def tube(self, radius, back, front):
        # Eight-sided barrel with a dark closed end: appearance only.
        loop=[(radius*math.cos(i*math.pi/4),radius*math.sin(i*math.pi/4)) for i in range(8)]
        self.prism(loop,back,front,STEEL)
        self.face([(x*.60,y*.60,front+.00001) for x,y in loop],DARK)


def outputs():
    m=Mesh()
    # Chamfered receiver; separate stock, grip and magazine silhouettes.
    m.prism([(-.05,-.06),(.05,-.06),(.06,-.04),(.06,.04),(.045,.065),(-.045,.065),(-.06,.04),(-.06,-.04)],-.58,-.29,STEEL)
    m.box(-.065,.065,-.07,.06,-.72,-.60,POLYMER)
    m.box(-.035,.035,-.04,.035,-.62,-.55,DARK)
    m.box(-.08,.08,-.08,.075,-.735,-.715,DARK)
    m.prism([(-.035,-.24),(.035,-.24),(.043,-.08),(-.025,-.08)],-.575,-.50,POLYMER)
    m.box(-.034,.034,-.27,-.075,-.455,-.35,EDGE)
    m.box(-.038,.038,-.27,-.25,-.46,-.345,DARK)
    m.box(-.055,.055,-.045,.045,-.30,-.13,POLYMER)
    for z in [-.27,-.23,-.19]: m.box(-.058,.058,-.049,-.040,z,z+.012,DARK)
    m.tube(.022,-.14,-.015); m.tube(.03,-.025,-.00001)
    m.box(-.035,.035,.064,.080,-.57,-.29,DARK)
    m.box(-.029,.029,.080,.108,-.55,-.52,EDGE)
    m.box(-.012,.012,.047,.092,-.17,-.15,EDGE)
    # Fictional amber identification plate, not an external logo or font.
    m.box(.060,.0601,-.012,.02,-.49,-.44,MARK)
    data={'assetSet':'service-rifle-v1','units':'metres','origin':'muzzle','forward':'+Z',
          'mesh':{'kind':'ServiceRifle','positions':m.positions,'normals':m.normals,'colors':m.colors,'triangles':m.triangles}}
    encoded=json.dumps(data,separators=(',',':'))+'\n'; digest=hashlib.sha256(encoded.encode()).hexdigest()
    if digest != FROZEN_V1_SHA256:
        raise SystemExit('service-rifle-v1 is frozen; introduce a new assetSet and retain v1. Actual SHA256: '+digest)
    provenance={'assetSet':data['assetSet'],'source':'Original fictional decorative game mesh; no external assets or real weapon specifications',
                'generator':'scripts/generate-service-rifle.py','dataSha256':digest,'triangles':len(m.triangles)//3,
                'origin':'accepted muzzle, +Z forward; no collider or gameplay changes'}
    return {UNITY/'service-rifle-v1.json':encoded,
            WEB/'service-rifle-data.js':'// Generated by scripts/generate-service-rifle.py; do not edit.\nexport const SERVICE_RIFLE = '+encoded.rstrip()+';\n',
            UNITY/'service-rifle-provenance.json':json.dumps(provenance,indent=2)+'\n'}


def main():
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    for path,content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=content: raise SystemExit('Generated rifle mismatch: '+str(path))
        else: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content,encoding='utf-8',newline='\n')
    print('Verified original service-rifle-v1 geometry / browser copy / provenance' if args.check else 'Generated service-rifle-v1 geometry / browser copy / provenance')


if __name__=='__main__': main()
