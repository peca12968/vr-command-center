"""Pin a new player fire presentation while reusing all frozen source meshes."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
UNITY=ROOT/'clients/unity/Assets/VrCommand/Resources/VrCommand'
WEB=ROOT/'src/VrCommand.Api/wwwroot/console'
PIN='187c7df5346419edadafa1cc74a04db0763dda268650e066dbbcaf8304e60ff0'
spec=importlib.util.spec_from_file_location('frozen_combat_effects',ROOT/'scripts/generate-combat-effects.py')
effects=importlib.util.module_from_spec(spec);spec.loader.exec_module(effects)

def outputs():
    effects.outputs()
    data={'assetSet':'player-fire-v1','units':'metres','origin':'accepted-player-shot','forward':'+Z','playerFireVersion':1,
        'weaponAssetSet':'weapon-actions-v1','weaponDataSha256':effects.armed.actions.PIN,
        'pulseAssetSet':'combat-effects-v1','pulseDataSha256':effects.PIN,'pulseScale':1.2,'flashTicks':3,
        'recoilMetres':[.014,.022,.012,.004]}
    encoded=json.dumps(data,separators=(',',':'))+'\n';digest=hashlib.sha256(encoded.encode()).hexdigest()
    if digest!=PIN:raise SystemExit('player-fire-v1 is frozen; use a new profile. SHA256: '+digest)
    provenance={'assetSet':data['assetSet'],'source':'Original deterministic player presentation; reuses frozen rifle/gloves/muzzle pulse; no external assets',
        'generator':'scripts/generate-player-fire.py','dataSha256':digest,'rifleTriangles':264,'gloveTriangles':240,'pulseTriangles':32,
        'scope':'Cosmetic child rifle/magazine recoil and saved-world flash only; no tracked-joint, gameplay, audio, light or collider change'}
    return {UNITY/'player-fire-v1.json':encoded,UNITY/'player-fire-provenance.json':json.dumps(provenance,indent=2)+'\n',
        WEB/'player-fire-data.js':'// Generated by scripts/generate-player-fire.py; do not edit.\nexport const PLAYER_FIRE = '+encoded.rstrip()+';\n'}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,value in outputs().items():
        if a.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=value:raise SystemExit('Player fire mismatch: '+str(path))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value,encoding='utf-8',newline='\n')
    print('Verified player-fire-v1 profile and provenance' if a.check else 'Generated player-fire-v1 profile and provenance')

if __name__=='__main__':main()
