"""Original, deterministic mono PCM effects; no sampled or third-party recordings."""
import argparse
import array
import hashlib
import io
import json
from pathlib import Path
import sys
import uuid
import wave

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "clients/unity/Assets/VrCommand/Audio"
NAMESPACE = uuid.UUID("36315c09-846e-4e4e-b0f7-e5597a9c559d")
RATE = 22050


def samples(thunder):
    count = RATE * 4
    state, slow, middle = (0x90AF32D1 if thunder else 0x4311BAC7), 0, 0
    result = []
    for index in range(count):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        state &= 0xFFFFFFFF
        noise = (state & 65535) - 32768
        slow += (noise - slow) // (100 if thunder else 16)
        middle += (noise - middle) // 12
        if thunder:
            value = slow * 8 + middle // 2
            if index < RATE // 5 and (index // 400) % 3 == 0:
                value += noise // 5
            value = value * (count - index) ** 2 // count ** 2
            value = value * min(index, 512) // 512
        else:
            value = slow * 2 + noise // 3
            value = value * min(index, count - 1 - index, 256) // 256
        result.append(value)
    peak = max(abs(value) for value in result)
    target = 22000 if thunder else 9000
    return [value * target // peak for value in result]


def wav(values):
    pcm = array.array("h", values)
    if sys.byteorder != "little":
        pcm.byteswap()
    stream = io.BytesIO()
    with wave.open(stream, "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(RATE)
        output.writeframes(pcm.tobytes())
    return stream.getvalue()


def meta(path, folder=False, text=False):
    guid = uuid.uuid5(NAMESPACE, path.relative_to(ROOT / "clients/unity").as_posix()).hex
    if folder:
        return f"fileFormatVersion: 2\nguid: {guid}\nfolderAsset: yes\nDefaultImporter:\n  externalObjects: {{}}\n  userData:\n  assetBundleName:\n  assetBundleVariant:\n".encode()
    if text:
        return f"fileFormatVersion: 2\nguid: {guid}\nTextScriptImporter:\n  externalObjects: {{}}\n  userData:\n  assetBundleName:\n  assetBundleVariant:\n".encode()
    return f"fileFormatVersion: 2\nguid: {guid}\nAudioImporter:\n  externalObjects: {{}}\n  serializedVersion: 7\n  forceToMono: 1\n  normalize: 0\n  preloadAudioData: 1\n  loadInBackground: 0\n  ambisonic: 0\n  userData:\n  assetBundleName:\n  assetBundleVariant:\n".encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify exact generated bytes without changing files")
    args = parser.parse_args()
    outputs = {DESTINATION.with_suffix(".meta"): meta(DESTINATION, True)}
    provenance = {"generator": "scripts/generate-weather-audio.py", "version": 1,
                  "source": "Original procedural noise synthesis; no third-party samples", "files": {}}
    for name, thunder in (("rain-loop.wav", False), ("thunder.wav", True)):
        values = samples(thunder)
        content = wav(values)
        outputs[DESTINATION / name] = content
        outputs[DESTINATION / (name + ".meta")] = meta(DESTINATION / name)
        provenance["files"][name] = {"sha256": hashlib.sha256(content).hexdigest(), "sampleRate": RATE,
            "channels": 1, "bitsPerSample": 16, "frames": len(values), "peak": max(abs(value) for value in values)}
    outputs[DESTINATION / "provenance.json"] = (json.dumps(provenance, indent=2) + "\n").encode()
    outputs[DESTINATION / "provenance.json.meta"] = meta(DESTINATION / "provenance.json", text=True)
    for path, content in outputs.items():
        if args.check:
            actual = path.read_bytes() if path.exists() else b""
            matches = actual == content
            if path.suffix == ".meta":
                matches = content.splitlines()[1] in actual.splitlines()  # Unity may expand importer settings.
            if not matches:
                raise SystemExit("Generated audio differs: " + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Preserve importer settings once Unity has imported an existing asset.
            if path.suffix != ".meta" or not path.exists():
                path.write_bytes(content)
    print("Verified weather audio bytes." if args.check else "Generated two original 4-second mono PCM weather effects.")
